import type { BoardPoint } from "./SceneFrame";
/** Pure ray crossing adapter for the frozen planner's polygon utility. */
export function indexedContainsPoint(polygon: readonly BoardPoint[], point: BoardPoint): boolean {
  let inside = false;
  for (let i=0,j=polygon.length-1;i<polygon.length;j=i++) {
    const a=polygon[i],b=polygon[j];
    if ((a.y>point.y)!==(b.y>point.y) && point.x<(b.x-a.x)*(point.y-a.y)/(b.y-a.y)+a.x) inside=!inside;
  }
  return inside;
}
